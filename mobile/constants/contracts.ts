// Helper to get contract address based on network
export function getContractAddress(
  network: string,
  contractName: keyof typeof SEPOLIA_CONTRACTS
): string {
  // For now, only Sepolia is supported
  if (network === "sepolia") {
    return SEPOLIA_CONTRACTS[contractName];
  }
  throw new Error(`Unsupported network: ${network}`);
}
