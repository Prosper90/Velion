const hre = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  console.log("🚀 Starting deployment to Sepolia testnet...\n");

  const [deployer] = await hre.ethers.getSigners();
  console.log("Deploying contracts with account:", deployer.address);

  const balance = await hre.ethers.provider.getBalance(deployer.address);
  console.log("Account balance:", hre.ethers.formatEther(balance), "ETH\n");

  if (balance === 0n) {
    console.error("❌ Error: Deployer account has no ETH!");
    console.log("Please fund your account from a Sepolia faucet:");
    console.log("- https://sepoliafaucet.com/");
    console.log("- https://faucet.quicknode.com/ethereum/sepolia");
    console.log("- https://www.alchemy.com/faucets/ethereum-sepolia");
    process.exit(1);
  }

  const deployments = {};

  // 1. Deploy Groth16 Verifiers (Generated by snarkjs)
  console.log("📝 Deploying ShieldVerifier (Groth16)...");
  const ShieldVerifier = await hre.ethers.getContractFactory("ShieldGroth16Verifier");
  const shieldVerifier = await ShieldVerifier.deploy();
  await shieldVerifier.waitForDeployment();
  const shieldVerifierAddress = await shieldVerifier.getAddress();
  console.log("✅ ShieldVerifier deployed to:", shieldVerifierAddress);
  deployments.ShieldVerifier = shieldVerifierAddress;

  console.log("\n📝 Deploying UnshieldVerifier (Groth16)...");
  const UnshieldVerifier = await hre.ethers.getContractFactory("UnshieldGroth16Verifier");
  const unshieldVerifier = await UnshieldVerifier.deploy();
  await unshieldVerifier.waitForDeployment();
  const unshieldVerifierAddress = await unshieldVerifier.getAddress();
  console.log("✅ UnshieldVerifier deployed to:", unshieldVerifierAddress);
  deployments.UnshieldVerifier = unshieldVerifierAddress;

  console.log("\n📝 Deploying TransferVerifier (Groth16)...");
  const TransferVerifier = await hre.ethers.getContractFactory("TransferGroth16Verifier");
  const transferVerifier = await TransferVerifier.deploy();
  await transferVerifier.waitForDeployment();
  const transferVerifierAddress = await transferVerifier.getAddress();
  console.log("✅ TransferVerifier deployed to:", transferVerifierAddress);
  deployments.TransferVerifier = transferVerifierAddress;

  // 2. Deploy Main Verifier contract (uses the 3 Groth16 verifiers)
  console.log("\n📝 Deploying Main Verifier contract...");
  const Verifier = await hre.ethers.getContractFactory("Verifier");
  const verifier = await Verifier.deploy(
    shieldVerifierAddress,
    unshieldVerifierAddress,
    transferVerifierAddress
  );
  await verifier.waitForDeployment();
  const verifierAddress = await verifier.getAddress();
  console.log("✅ Verifier deployed to:", verifierAddress);
  deployments.Verifier = verifierAddress;

  // 3. Deploy PrivacyPoolV2 (with ERC20 support!)
  console.log("\n📝 Deploying PrivacyPoolV2 contract (with ERC20 support)...");
  const PrivacyPoolV2 = await hre.ethers.getContractFactory("PrivacyPoolV2");
  const privacyPool = await PrivacyPoolV2.deploy(verifierAddress);
  await privacyPool.waitForDeployment();
  const privacyPoolAddress = await privacyPool.getAddress();
  console.log("✅ PrivacyPoolV2 deployed to:", privacyPoolAddress);
  deployments.PrivacyPoolV2 = privacyPoolAddress;

  // 4. RelayerRegistry removed - using off-chain relayer service only
  console.log("\n📡 Relayer service will be used off-chain (no on-chain registry)");

  // 5. Deploy Governance Contract
  console.log("\n🏛️  Deploying Governance contract...");
  const quorum = 1;
  const votingPeriod = 86400; // 1 day
  const Governance = await hre.ethers.getContractFactory("Governance");
  const governance = await Governance.deploy(quorum, votingPeriod);
  await governance.waitForDeployment();
  const governanceAddress = await governance.getAddress();
  deployments.Governance = governanceAddress;
  console.log(`✅ Governance deployed to: ${governanceAddress}`);

  // 6. Deploy EmergencyExit Contract
  console.log("\n🚨 Deploying EmergencyExit contract...");
  const EmergencyExit = await hre.ethers.getContractFactory("EmergencyExit");
  const emergencyExit = await EmergencyExit.deploy(
    privacyPoolAddress,
    verifierAddress
  );
  await emergencyExit.waitForDeployment();
  const emergencyExitAddress = await emergencyExit.getAddress();
  deployments.EmergencyExit = emergencyExitAddress;
  console.log(`✅ EmergencyExit deployed to: ${emergencyExitAddress}`);

  // 7. Contract initialization (RelayerRegistry removed)
  console.log("\n⚙️  Contract initialization...");

  // 8. Whitelist common tokens (optional - can be done later via owner)
  console.log("\n📝 Whitelisting common ERC20 tokens...");

  // Sepolia USDC (example - update with actual Sepolia token addresses)
  const SEPOLIA_USDC = "0x1c7D4B196Cb0C7B01d743Fbc6116a902379C7238"; // Example Sepolia USDC
  const SEPOLIA_USDT = "0xaA8E23Fb1079EA71e0a56F48a2aA51851D8433D0"; // Example Sepolia USDT

  try {
    // ETH is already whitelisted by default in constructor
    console.log("✅ ETH whitelisted by default");

    // Whitelist USDC
    await privacyPool.setTokenWhitelist(SEPOLIA_USDC, true);
    console.log("✅ USDC whitelisted:", SEPOLIA_USDC);

    // Whitelist USDT
    await privacyPool.setTokenWhitelist(SEPOLIA_USDT, true);
    console.log("✅ USDT whitelisted:", SEPOLIA_USDT);
  } catch (error) {
    console.log("⚠️  Token whitelisting skipped (can be done manually later)");
  }

  // Save deployment addresses
  const deploymentData = {
    network: "sepolia",
    chainId: 11155111,
    deployer: deployer.address,
    timestamp: new Date().toISOString(),
    contracts: deployments,
    supportedTokens: {
      ETH: "0x0000000000000000000000000000000000000000",
      USDC: SEPOLIA_USDC,
      USDT: SEPOLIA_USDT,
    },
  };

  const deploymentDir = path.join(__dirname, "../deployments");
  if (!fs.existsSync(deploymentDir)) {
    fs.mkdirSync(deploymentDir, { recursive: true });
  }

  const deploymentFile = path.join(deploymentDir, "sepolia-deployment.json");
  fs.writeFileSync(deploymentFile, JSON.stringify(deploymentData, null, 2));

  console.log("\n" + "=".repeat(70));
  console.log("✅ Deployment completed successfully!");
  console.log("=".repeat(70));
  console.log("\n📋 Deployment Summary:");
  console.log("Network:", "Sepolia Testnet");
  console.log("Chain ID:", "11155111");
  console.log("Deployer:", deployer.address);
  console.log("\n📄 Contract Addresses:");
  Object.entries(deployments).forEach(([name, address]) => {
    console.log(`${name}:`.padEnd(25), address);
  });

  console.log("\n💰 Supported Tokens:");
  console.log("ETH:".padEnd(25), "Native (whitelisted)");
  console.log("USDC:".padEnd(25), SEPOLIA_USDC);
  console.log("USDT:".padEnd(25), SEPOLIA_USDT);

  console.log("\n💾 Deployment data saved to:", deploymentFile);

  console.log("\n🔍 Verification Commands:");
  console.log("ShieldVerifier:", `npx hardhat verify --network sepolia ${shieldVerifierAddress}`);
  console.log("UnshieldVerifier:", `npx hardhat verify --network sepolia ${unshieldVerifierAddress}`);
  console.log("TransferVerifier:", `npx hardhat verify --network sepolia ${transferVerifierAddress}`);
  console.log("Verifier:", `npx hardhat verify --network sepolia ${verifierAddress} ${shieldVerifierAddress} ${unshieldVerifierAddress} ${transferVerifierAddress}`);
  console.log("PrivacyPoolV2:", `npx hardhat verify --network sepolia ${privacyPoolAddress} ${verifierAddress}`);

  console.log("\n📝 Next Steps:");
  console.log("1. Update mobile/constants/contracts.ts with these addresses");
  console.log("2. Update backend .env with PRIVACY_POOL_ADDRESS");
  console.log("3. Whitelist additional ERC20 tokens if needed:");
  console.log("   privacyPool.setTokenWhitelist(tokenAddress, true)");
  console.log("4. Test shield/unshield flows for ETH and ERC20 tokens");

  console.log("\n✨ PrivacyPoolV2 Features:");
  console.log("• Shield ETH with shieldETH(commitment)");
  console.log("• Shield ERC20 with shieldERC20(token, amount, commitment)");
  console.log("• Unshield with unshield(commitment, nullifier, recipient, amount, token, proof)");
  console.log("• Private Transfer with privateTransfer(inputCommitment, inputNullifier, outputCommitment, token, proof)");
  console.log("• Support for USDC, USDT, DAI, and other ERC20 tokens");
  console.log("• Per-token accounting with getTotalShielded(token) and getTotalUnshielded(token)");

  console.log("\n" + "=".repeat(70));
}

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error("\n❌ Deployment failed:");
    console.error(error);
    process.exit(1);
  });
